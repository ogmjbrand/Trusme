import { NextResponse } from "next/server";
import { z } from "zod";
import { PDFDocument, StandardFonts, rgb } from "pdf-lib";
import { getWorkspace } from "@/lib/auth/context";
import { toMajorString } from "@/lib/money";

export const runtime = "nodejs";

// Standard PDF fonts cannot render symbols such as ₦, so amounts use ISO codes.
function money(minor: number, currency: string) {
  const [whole, frac] = toMajorString(minor, currency).split(".");
  return `${currency} ${Number(whole).toLocaleString("en-US")}${frac ? "." + frac : ""}`;
}
function ascii(s: string) {
  return s.replace(/[^\x20-\x7E]/g, "?");
}

export async function GET(_req: Request, { params }: { params: Promise<{ id: string }> }) {
  const { id } = await params;
  if (!z.string().uuid().safeParse(id).success) return NextResponse.json({ error: "Not found" }, { status: 404 });
  const ws = await getWorkspace();
  const { data: inv } = await ws.supabase.from("invoices").select("*, customers(name, email, address)").eq("id", id).eq("organization_id", ws.org.organizationId).maybeSingle();
  if (!inv) return NextResponse.json({ error: "Not found" }, { status: 404 });
  const { data: items } = await ws.supabase.from("invoice_items").select("*").eq("invoice_id", id).order("position");

  const pdf = await PDFDocument.create();
  const page = pdf.addPage([595, 842]);
  const font = await pdf.embedFont(StandardFonts.Helvetica);
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);
  const ink = rgb(0.1, 0.12, 0.13);
  const muted = rgb(0.42, 0.46, 0.49);
  const brand = rgb(0.02, 0.59, 0.41);
  let y = 790;
  const text = (s: string, x: number, size = 10, f = font, color = ink) => page.drawText(ascii(s), { x, y, size, font: f, color });
  const right = (s: string, xr: number, size = 10, f = font, color = ink) => page.drawText(ascii(s), { x: xr - f.widthOfTextAtSize(ascii(s), size), y, size, font: f, color });

  text(ws.org.name, 50, 16, bold);
  right("INVOICE", 545, 16, bold, brand);
  y -= 22;
  right(String(inv.invoice_number), 545, 11, bold);
  y -= 16;
  right(`Status: ${String(inv.status).replace("_", " ")}`, 545, 9, font, muted);
  y -= 30;
  text("Bill to", 50, 9, font, muted);
  text("Issue date", 360, 9, font, muted);
  right(String(inv.issue_date), 545, 9);
  y -= 14;
  const c = inv.customers as { name: string; email: string | null; address: string | null } | null;
  text(c?.name ?? "", 50, 11, bold);
  text("Due date", 360, 9, font, muted);
  right(String(inv.due_date), 545, 9);
  y -= 14;
  if (c?.email) { text(c.email, 50, 9, font, muted); y -= 12; }
  if (c?.address) { text(c.address.slice(0, 80), 50, 9, font, muted); y -= 12; }
  y -= 24;

  page.drawRectangle({ x: 50, y: y - 6, width: 495, height: 20, color: rgb(0.95, 0.96, 0.96) });
  text("Description", 56, 9, bold);
  right("Qty", 350, 9, bold);
  right("Unit price", 440, 9, bold);
  right("Amount", 539, 9, bold);
  y -= 24;
  for (const it of items ?? []) {
    if (y < 140) break;
    text(String(it.description).slice(0, 55), 56, 9);
    right(String(Number(it.quantity)), 350, 9);
    right(money(it.unit_price_minor, inv.currency), 440, 9);
    right(money(Math.round(Number(it.quantity) * it.unit_price_minor), inv.currency), 539, 9);
    y -= 18;
  }
  y -= 10;
  page.drawLine({ start: { x: 330, y: y + 6 }, end: { x: 545, y: y + 6 }, thickness: 0.5, color: muted });
  const totals: [string, number, boolean][] = [
    ["Subtotal", inv.subtotal_minor, false],
    ["Tax", inv.tax_minor, false],
    ...(inv.discount_minor ? ([["Discount", -inv.discount_minor, false]] as [string, number, boolean][]) : []),
    ["Total", inv.total_minor, true],
    ["Paid", inv.amount_paid_minor, false],
    ["Balance due", inv.total_minor - inv.amount_paid_minor, true],
  ];
  for (const [label, v, strong] of totals) {
    y -= 16;
    text(label, 340, 10, strong ? bold : font, strong ? ink : muted);
    right(money(v, inv.currency), 539, 10, strong ? bold : font);
  }
  if (inv.notes) {
    y -= 36;
    text("Notes", 50, 9, bold);
    for (const line of String(inv.notes).split("\n").slice(0, 8)) {
      y -= 13;
      text(line.slice(0, 95), 50, 9, font, muted);
    }
  }
  page.drawText(ascii(`Generated by TrustOS on ${new Date().toISOString().slice(0, 10)}${inv.is_sample ? " - SAMPLE DATA, NOT A REAL INVOICE" : ""}`), { x: 50, y: 40, size: 8, font, color: muted });

  const bytes = await pdf.save();
  return new Response(Buffer.from(bytes), {
    headers: {
      "Content-Type": "application/pdf",
      "Content-Disposition": `attachment; filename="${inv.invoice_number}.pdf"`,
      "Cache-Control": "no-store",
    },
  });
}
